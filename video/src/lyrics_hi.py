# Syllabified Hindi lyrics. '|' splits syllables inside a word; spaces split words.
NUM = ['एक', 'दो', 'तीन', 'चार', 'पाँच']
def verse(n):
    pl = n > 1
    l1 = f"{NUM[n-1]} नन्|{'हे' if pl else 'हा'} हा|थी खेल|ने को च|{'ले' if pl else 'ला'}"
    l2 = "मक|ड़ी के जा|ले पर झूल|ने"
    if n < 5:
        l3 = "खूब म|ज़ा आ|या " + ("उन्|हें" if pl else "उ|से")
        l4 = "दूस|रे हा|थी को उस|ने बु|ला लि|या" if n == 1 else "एक और हा|थी को उन्|हों|ने बु|ला|या"
    else:
        l3 = "उछ|ले कू|दे खूब म|ज़ा"
        l4 = "पर जा|ला खिंच|ता ग|या खिंच|ता ग|या"
    return [l1, l2, l3, l4]
